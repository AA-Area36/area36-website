import { describe, expect, it } from "vitest"
import { applyCommand, assessBallot, commandSchema, createElectionState, reviewOffice, tally, type Vote } from "./model"

const votes = (...totals: number[]): Vote[] => totals.map((inPerson, index) => ({ candidateId: String(index + 1), inPerson, online: 0 }))
const run = (state: ReturnType<typeof createElectionState>, command: Parameters<typeof applyCommand>[1]) => applyCommand(state, command.type === "finalize" && command.expectedVotes === undefined ? { ...command, expectedVotes: Math.max(1, tally(command.votes, command.noCandidate).total) } : command, "teller@area36.org", "2026-10-10T12:00:00Z")
const setup = () => run(createElectionState("Officer elections", "2026-10-10"), { type: "candidates", officeIndex: 0, names: ["Alex", "Blair", "Casey", "Drew"] })

describe("Third Legacy procedure", () => {
  it("combines both channels and uses the exact two-thirds threshold", () => {
    expect(tally([{ candidateId: "a", inPerson: 20, online: 3 }, { candidateId: "b", inPerson: 10, online: 1 }])).toMatchObject({ total: 34, threshold: 23 })
    expect(assessBallot(1, votes(22, 12)).winnerId).toBeNull()
    expect(assessBallot(1, votes(23, 11)).winnerId).toBe("1")
    expect(assessBallot(1, votes(2, 1)).winnerId).toBe("1")
    expect(assessBallot(1, votes(0, 0)).winnerId).toBeNull()
  })
  it("keeps all candidates after ballot 1 and includes the exact one-fifth boundary", () => {
    expect(assessBallot(1, votes(50, 30, 15, 5)).remainingIds).toEqual(["1", "2", "3", "4"])
    expect(assessBallot(2, votes(40, 21, 20, 19)).remainingIds).toEqual(["1", "2", "3"])
  })
  it("protects every tied runner-up even below the withdrawal threshold", () => {
    expect(assessBallot(2, votes(19, 4, 4, 4)).remainingIds).toEqual(["1", "2", "3", "4"])
    expect(assessBallot(3, votes(50, 20, 20, 10)).remainingIds).toEqual(["1", "2", "3"])
    expect(assessBallot(3, votes(40, 40, 10, 10)).remainingIds).toEqual(["1", "2"])
    expect(assessBallot(3, votes(10, 10, 10)).remainingIds).toEqual(["1", "2", "3"])
  })
  it("uses exact one-third arithmetic and only withdraws the lowest unprotected totals after ballot 4", () => {
    expect(assessBallot(3, votes(4, 3, 2)).remainingIds).toEqual(["1", "2"])
    expect(assessBallot(4, votes(40, 25, 20, 15)).remainingIds).toEqual(["1", "2", "3"])
    expect(assessBallot(4, votes(40, 20, 20, 20)).remainingIds).toEqual(["1", "2", "3", "4"])
    expect(assessBallot(4, votes(55, 45)).remainingIds).toEqual(["1", "2"])
  })
  it("keeps tied leaders, or all tied runners-up, for the hat after ballot 5", () => {
    expect(assessBallot(5, votes(35, 35, 30)).remainingIds).toEqual(["1", "2"])
    expect(assessBallot(5, votes(40, 20, 20, 20)).remainingIds).toEqual(["1", "2", "3", "4"])
  })
  it("guides all five ballots, requires the motion, and records a physical hat result", () => {
    let state = setup()
    for (let number = 1; number <= 4; number++) state = run(state, { type: "finalize", officeIndex: 0, votes: votes(30, 30, 30, 30) })
    expect(state.offices[0].status).toBe("motion")
    expect(() => run(state, { type: "finalize", officeIndex: 0, votes: votes(30, 30, 30, 30) })).toThrow("not accepting")
    const declined = run(state, { type: "motion", officeIndex: 0, approved: false })
    expect(declined.offices[0].status).toBe("hat")
    state = run(state, { type: "motion", officeIndex: 0, approved: true })
    state = run(state, { type: "finalize", officeIndex: 0, votes: votes(30, 30, 30, 30) })
    expect(state.offices[0].status).toBe("hat")
    expect(() => run(state, { type: "hat", officeIndex: 0, candidateId: "missing" })).toThrow("remaining candidate")
    state = run(state, { type: "hat", officeIndex: 0, candidateId: "2" })
    expect(state.offices[0]).toMatchObject({ status: "elected", winnerId: "2", electionMethod: "hat", fifthBallotApproved: true })
    expect(state.offices[1].status).toBe("setup")
  })
  it("corrects a ballot in place and recalculates its outcome", () => {
    const original = setup()
    const elected = run(original, { type: "finalize", officeIndex: 0, votes: votes(70, 20, 5, 5) })
    const corrected = run(elected, { type: "correct", officeIndex: 0, ballotNumber: 1, votes: votes(60, 20, 10, 10), expectedVotes: 100, reason: "Teller corrected the count" })
    expect(corrected.offices[0]).toMatchObject({ status: "balloting", winnerId: null, electionMethod: null, eligibleIds: ["1", "2", "3", "4"] })
    expect(corrected.offices[0].ballots).toHaveLength(1)
    expect(corrected.offices[0].ballots[0].votes).toEqual(votes(60, 20, 10, 10))
    expect(elected.offices[0].winnerId).toBe("1")
    expect(original.offices[0].ballots).toHaveLength(0)
  })
  it("rejects missing or repeated candidates, duplicate names, and invalid counts", () => {
    const state = setup()
    expect(() => run(state, { type: "draft", officeIndex: 0, votes: votes(1, 2) })).toThrow("every candidate")
    expect(() => run(state, { type: "draft", officeIndex: 0, votes: [votes(1)[0], votes(1)[0], ...votes(1, 1).map(vote => ({ ...vote, candidateId: "3" }))] })).toThrow("every candidate")
    expect(() => run(state, { type: "candidates", officeIndex: 0, names: ["Alex", "alex"] })).toThrow("distinct")
    for (const invalid of [-1, 1.5, Infinity, NaN, 100_001]) expect(commandSchema.safeParse({ type: "draft", officeIndex: 0, votes: [{ candidateId: "1", inPerson: invalid, online: 0 }] }).success).toBe(false)
  })
})


describe("turnout and direct corrections", () => {
  it("includes X in percentages and the election threshold, while X cannot win", () => {
    const result = assessBallot(1, votes(60, 30), { inPerson: 5, online: 5 }, 100)
    expect(result).toMatchObject({ total: 100, candidateTotal: 90, threshold: 67, noCandidateShare: 0.1, difference: 0, winnerId: null })
    expect(result.rows[0].share).toBe(0.6)
    expect(assessBallot(1, votes(0, 0), { inPerson: 100, online: 0 }, 100).winnerId).toBeNull()
  })
  it("requires an expected count and carries it to later ballots and new offices", () => {
    let state = setup()
    const command = { type: "finalize" as const, officeIndex: 0, votes: votes(40, 30, 20, 0), noCandidate: { inPerson: 4, online: 6 }, expectedVotes: 100 }
    expect(() => run(state, { ...command, expectedVotes: null })).toThrow("Expected votes")
    state = run(state, command)
    expect(state.offices[0].expectedVotes).toBe(100)
    expect(state.offices[0].draftNoCandidate).toEqual({ inPerson: 0, online: 0 })
    state = run(state, { type: "candidates", officeIndex: 1, names: ["Elliot", "Finley"] })
    expect(state.offices[1].expectedVotes).toBe(100)
    expect(state.offices[0].ballots[0]).toMatchObject({ expectedVotes: 100, noCandidate: { inPerson: 4, online: 6 } })
  })
  it.each([0, 90, 110])("closes a ballot with %i recorded votes against 100 expected and allows the next ballot", total => {
    let state = run(setup(), { type: "finalize", officeIndex: 0, votes: votes(total / 2, total / 2, 0, 0), expectedVotes: 100 })
    expect(state.offices[0]).toMatchObject({ status: "balloting", expectedVotes: 100, winnerId: null })
    expect(tally(state.offices[0].ballots[0].votes, state.offices[0].ballots[0].noCandidate, state.offices[0].ballots[0].expectedVotes).difference).toBe(total - 100)
    expect(reviewOffice(state.offices[0]).issues).toEqual([])
    state = applyCommand(state, { type: "finalize", officeIndex: 0, votes: votes(40, 30, 20, 10) }, "teller", "now")
    expect(state.offices[0].ballots).toHaveLength(2)
    expect(state.offices[0].ballots[1].expectedVotes).toBe(100)
  })
  function threeBallots() {
    let state = setup()
    state = run(state, { type: "finalize", officeIndex: 0, votes: votes(40, 30, 20, 10) })
    state = run(state, { type: "finalize", officeIndex: 0, votes: votes(40, 30, 20, 10) })
    state = run(state, { type: "finalize", officeIndex: 0, votes: votes(40, 35, 25) })
    state = run(state, { type: "draft", officeIndex: 0, votes: votes(20, 30), expectedVotes: 100 })
    state = run(state, { type: "candidates", officeIndex: 1, names: ["Elliot", "Finley"] })
    return run(state, { type: "draft", officeIndex: 1, votes: votes(15, 25), expectedVotes: 100 })
  }
  it("preserves later ballots, both current drafts, and another office when correcting ballot 1", () => {
    const state = threeBallots()
    const corrected = run(state, { type: "correct", officeIndex: 0, ballotNumber: 1, votes: votes(45, 25, 20, 10), expectedVotes: 100, reason: "Corrected ballot one totals" })
    expect(corrected.offices[0].ballots.slice(1)).toEqual(state.offices[0].ballots.slice(1))
    expect(corrected.offices[0].draft).toEqual(state.offices[0].draft)
    expect(corrected.offices[1]).toEqual(state.offices[1])
    expect(reviewOffice(corrected.offices[0]).issues).toEqual([])
  })
  it.each([90, 110])("allows a correction with %i recorded votes against 100 expected without blocking later progress", total => {
    const state = threeBallots()
    let corrected = run(state, { type: "correct", officeIndex: 0, ballotNumber: 1, votes: votes(total / 2, total / 2, 0, 0), expectedVotes: 100, reason: "Reviewed turnout difference" })
    expect(corrected.offices[0].ballots.slice(1)).toEqual(state.offices[0].ballots.slice(1))
    expect(corrected.offices[0].draft).toEqual(state.offices[0].draft)
    expect(corrected.offices[1]).toEqual(state.offices[1])
    expect(reviewOffice(corrected.offices[0]).issues).toEqual([])
    corrected = run(corrected, { type: "finalize", officeIndex: 0, votes: votes(55, 45), expectedVotes: 100 })
    expect(corrected.offices[0].status).toBe("motion")
  })
  it("flags a changed candidate list without erasing the dependent ballot, and allows direct repair", () => {
    const state = threeBallots()
    let corrected = run(state, { type: "correct", officeIndex: 0, ballotNumber: 2, votes: votes(46, 35, 19, 0), expectedVotes: 100, reason: "Corrected second ballot totals" })
    expect(corrected.offices[0].ballots[2]).toEqual(state.offices[0].ballots[2])
    expect(reviewOffice(corrected.offices[0]).issues).toMatchObject([{ ballotNumber: 3 }])
    expect(() => run(corrected, { type: "finalize", officeIndex: 0, votes: votes(60, 40) })).toThrow("Review")
    corrected = run(corrected, { type: "correct", officeIndex: 0, ballotNumber: 3, votes: votes(55, 45), expectedVotes: 100, reason: "Reviewed affected candidate list" })
    expect(reviewOffice(corrected.offices[0]).issues).toEqual([])
    expect(corrected.offices[0].ballots).toHaveLength(3)
    expect(corrected.offices[0].draft).toEqual(state.offices[0].draft)
    expect(corrected.offices[1]).toEqual(state.offices[1])
  })
  it("retains later records when an older correction produces a winner, and restores them if corrected again", () => {
    const state = threeBallots()
    let corrected = run(state, { type: "correct", officeIndex: 0, ballotNumber: 1, votes: votes(70, 20, 5, 5), expectedVotes: 100, reason: "Older ballot elects a candidate" })
    expect(corrected.offices[0]).toMatchObject({ status: "elected", winnerId: "1" })
    expect(reviewOffice(corrected.offices[0]).archivedBallots).toEqual([2, 3])
    expect(corrected.offices[0].ballots.slice(1)).toEqual(state.offices[0].ballots.slice(1))
    corrected = run(corrected, { type: "correct", officeIndex: 0, ballotNumber: 1, votes: votes(40, 30, 20, 10), expectedVotes: 100, reason: "Reviewed original ballot totals" })
    expect(corrected.offices[0].status).toBe("balloting")
    expect(reviewOffice(corrected.offices[0]).archivedBallots).toEqual([])
    expect(corrected.offices[0].draft).toEqual(state.offices[0].draft)
  })
  it("rejects pasted multi-line candidate names", () => {
    expect(commandSchema.safeParse({ type: "candidates", officeIndex: 0, names: ["Alex\nBlair"] }).success).toBe(false)
  })
})
